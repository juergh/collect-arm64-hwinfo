    @staticmethod
    def _load_id_database(kind):
        candidates = {
            "pci": (
                "/usr/share/hwdata/pci.ids",
                "/usr/share/misc/pci.ids",
                "/usr/share/pci.ids",
            ),
            "usb": (
                "/usr/share/hwdata/usb.ids",
                "/usr/share/misc/usb.ids",
                "/var/lib/usbutils/usb.ids",
            ),
        }

        database_path = next((Path(path) for path in candidates[kind] if Path(path).is_file()), None)
        if not database_path:
            return {}, {}, None

        vendors = {}
        devices = {}
        current_vendor = None
        for line in database_path.read_text(encoding="utf-8", errors="replace").splitlines():
            vendor_match = re.match(r"^([0-9A-Fa-f]{4})\s{2,}(.+)$", line)
            if vendor_match:
                current_vendor = vendor_match.group(1).lower()
                vendors[current_vendor] = vendor_match.group(2).strip()
                continue

            if current_vendor and line.startswith("\t") and not line.startswith("\t\t"):
                device_match = re.match(r"^\t([0-9A-Fa-f]{4})\s{2,}(.+)$", line)
                if device_match:
                    devices[(current_vendor, device_match.group(1).lower())] = device_match.group(2).strip()
            elif line and not line.startswith(("#", "\t")):
                current_vendor = None

        return vendors, devices, str(database_path)

    def _parse_pci_and_pnp(self):
        pci_props_records = self._get_records("pnp", "pci_properties")
        entity_records = self._get_records("pnp", "entities")

        # Map PCI location properties by normalized uppercase InstanceId
        pci_locations = {}
        for p in pci_props_records:
            inst = p.get("InstanceId", "").upper()
            if inst:
                pci_locations[inst] = p

        pci_vendors, pci_names, pci_ids_source = self._load_id_database("pci")
        usb_vendors, usb_names, usb_ids_source = self._load_id_database("usb")

        for e in entity_records:
            caption = e.get("Caption") or "Unknown Device"
            pnp_cls = e.get("PNPClass") or "Unknown"
            device_id = e.get("DeviceID") or ""
            hw_ids = e.get("HardwareID") or []
            hw_ids_str = " ".join(hw_ids)

            # Match PCI devices
            pci_m = re.search(
                r"PCI\\VEN_([0-9A-Fa-f]{4})&DEV_([0-9A-Fa-f]{4})(?:&SUBSYS_([0-9A-Fa-f]{8}))?",
                hw_ids_str if hw_ids else device_id,
            )
            if pci_m:
                vid = pci_m.group(1).lower()
                did = pci_m.group(2).lower()
                subsys = pci_m.group(3).lower() if pci_m.group(3) else None
                canonical_device = pci_names.get((vid, did))
                canonical_vendor = pci_vendors.get(vid)
                resolved_caption = (
                    " ".join(filter(None, (canonical_vendor, canonical_device))) if canonical_device else caption
                )

                loc_data = pci_locations.get(device_id.upper(), {})
                loc_paths_arr = loc_data.get("DEVPKEY_Device_LocationPaths", [])
                loc_paths = ", ".join(loc_paths_arr) if loc_paths_arr else None

                root_m = re.search(r"#ACPI\((PCI[0-9A-Za-z]+)\)", loc_paths) if loc_paths else None
                acpi_root = root_m.group(1) if root_m else None
                dt_port = (
                    f"&{acpi_root.lower()}_port0"
                    if (acpi_root and "PCI4" in acpi_root)
                    else (f"&{acpi_root.lower()}" if acpi_root else None)
                )

                # Decode device/function from DEVPKEY_Device_Address
                raw_addr = loc_data.get("DEVPKEY_Device_Address")
                addr_desc = None
                if raw_addr is not None:
                    try:
                        addr_int = int(raw_addr)
                        dev_num = (addr_int >> 16) & 0xFFFF
                        func_num = addr_int & 0xFFFF
                        addr_desc = f"{addr_int} (Device: {dev_num}, Function: {func_num})"
                    except Exception:
                        addr_desc = str(raw_addr)

                bus_num = loc_data.get("DEVPKEY_Device_BusNumber")
                pci_entry = {
                    "caption": resolved_caption,
                    "collector_caption": caption,
                    "caption_source": pci_ids_source if canonical_device else "inventory.json:pnp.entities",
                    "caption_status": "inferred" if canonical_device else "observed",
                    "class": pnp_cls,
                    "vendor_id": vid,
                    "device_id": did,
                    "subsystem_id": subsys,
                    "device_id_str": device_id,
                    "location_paths": loc_paths,
                    "bus_number": str(bus_num) if bus_num is not None else None,
                    "address": addr_desc,
                    "acpi_root_port": acpi_root,
                    "dt_pcie_port": dt_port,
                    "source": "inventory.json:pnp.entities",
                    "status": "runtime-observed",
                }
                self.facts["pci_devices"].append(pci_entry)

                network_names = f"{resolved_caption} {caption}"
                if pnp_cls == "Net" and re.search(r"Wi-Fi|Wireless|WLAN|802\.11", network_names, re.IGNORECASE):
                    if not self.facts.get("wifi"):
                        self.facts["wifi"] = pci_entry

                if (
                    pnp_cls == "Net"
                    and re.search(r"Ethernet|GbE|LAN|Realtek", network_names, re.IGNORECASE)
                    and not re.search(r"Wi-Fi|Wireless|WLAN", network_names, re.IGNORECASE)
                ):
                    if not self.facts.get("ethernet"):
                        self.facts["ethernet"] = pci_entry

            # Match USB devices
            usb_m = re.search(r"USB\\VID_([0-9A-Fa-f]{4})&PID_([0-9A-Fa-f]{4})", hw_ids_str if hw_ids else device_id)
            if usb_m:
                vid = usb_m.group(1).lower()
                pid = usb_m.group(2).lower()
                canonical_device = usb_names.get((vid, pid))
                canonical_vendor = usb_vendors.get(vid)
                resolved_caption = (
                    " ".join(filter(None, (canonical_vendor, canonical_device))) if canonical_device else caption
                )
                self.facts["usb_devices"].append(
                    {
                        "caption": resolved_caption,
                        "collector_caption": caption,
                        "caption_source": usb_ids_source if canonical_device else "inventory.json:pnp.entities",
                        "caption_status": "inferred" if canonical_device else "observed",
                        "class": pnp_cls,
                        "vendor_id": vid,
                        "product_id": pid,
                        "device_id_str": device_id,
                        "source": "inventory.json:pnp.entities",
                        "status": "runtime-observed",
                    }
                )

