class DslIndex:
    """Brace-aware index of ACPI DSL text for reading the objects that belong to a device."""

    def __init__(self, text):
        self.text = text
        self._close = {}
        self._parent = {}
        stack = []
        for m in re.finditer(r'"(?:\\.|[^"\\])*"|/\*.*?\*/|//[^\n]*|[{}]', text, re.DOTALL):
            if m.group() == "{":
                self._parent[m.start()] = stack[-1] if stack else None
                stack.append(m.start())
            elif m.group() == "}" and stack:
                self._close[stack.pop()] = m.start()
        self._device_names = {}
        for name, open_index in self.objects("Device"):
            self._device_names[open_index] = name

    def objects(self, kind):
        """Yield (name, index of the opening brace) for every object of a kind such as Device or ThermalZone."""
        for m in re.finditer(rf"\b{kind}\s*\(\s*([A-Za-z0-9_]+)\s*\)\s*\{{", self.text):
            if m.end() - 1 in self._close:
                yield m.group(1), m.end() - 1

    def devices(self):
        return self.objects("Device")

    def body(self, open_index):
        return self.text[open_index + 1 : self._close[open_index]]

    def path(self, dev_open):
        """Return the ACPI path of a device, assuming that all of its ancestors are devices below \\_SB."""
        names = []
        node = dev_open
        while node is not None:
            if node in self._device_names:
                names.append(self._device_names[node])
            node = self._parent.get(node)
        return "\\_SB." + ".".join(reversed(names))

    def own_block(self, dev_open, header):
        """Return the body of the braced block declared directly in the device whose header regex matches."""
        for m in re.finditer(header, self.body(dev_open)):
            open_index = dev_open + m.end()
            if self._parent.get(open_index) == dev_open and open_index in self._close:
                return self.body(open_index)
        return None

    def own_method(self, dev_open, name):
        """Return the body of a method declared directly in the device, not in a nested device."""
        return self.own_block(dev_open, rf"Method\s*\(\s*{name}\b[^{{]*\{{")


class HwInfoParser:
    def __init__(self, target_path: str):
        self.target_path = Path(target_path).resolve()
        self.temp_dir = None
        self.work_dir = None
        self.acpi_staging_dir = None

        self.inventory = {}
        self.facts = {
            "system": {},
            "processor": {},
            "soc": {},
            "controllers": {},
            "peripherals": [],
            "gpio_devices": [],
            "thermal_zones": [],
            "usb_ports": [],
            "acpi_properties": [],
            "pci_devices": [],
            "usb_devices": [],
            "wifi": None,
            "ethernet": None,
            "display": {},
            "battery": {},
            "hwids": {},
        }

        self.missing = []

    def __enter__(self):
        if not self.target_path.exists():
            raise FileNotFoundError(f"Target path does not exist: {self.target_path}")

        if self.target_path.is_file() and zipfile.is_zipfile(self.target_path):
            self.temp_dir = tempfile.mkdtemp(prefix="hwinfo_parse_")
            temp_root = os.path.realpath(self.temp_dir)
            with zipfile.ZipFile(self.target_path, "r") as z:
                for member in z.infolist():
                    # Archives created on Windows (e.g. by Compress-Archive) use backslashes.
                    # Normalize separators so files and directories are extracted properly on POSIX.
                    norm_name = member.filename.replace("\\", "/")
                    if not norm_name or norm_name == "/":
                        continue
                    member.filename = norm_name
                    target = os.path.realpath(os.path.join(self.temp_dir, member.filename))
                    if target != temp_root and not target.startswith(temp_root + os.sep):
                        raise RuntimeError(f"Zip slip attempt detected in archive: {member.filename}")
                    if target == temp_root:
                        continue
                    z.extract(member, self.temp_dir)
            self.work_dir = Path(self.temp_dir)
        elif self.target_path.is_dir():
            self.work_dir = self.target_path
        else:
            raise ValueError(f"Target must be a .zip archive or a directory: {self.target_path}")

        self._load_inventory()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        if self.temp_dir and os.path.exists(self.temp_dir):
            shutil.rmtree(self.temp_dir, ignore_errors=True)
        if self.acpi_staging_dir and os.path.exists(self.acpi_staging_dir):
            shutil.rmtree(self.acpi_staging_dir, ignore_errors=True)

    def _load_inventory(self):
        inv_path = self.work_dir / "inventory.json"
        if not inv_path.is_file():
            # Search recursively in case the zip had a wrapper directory
            found = sorted(self.work_dir.glob("**/inventory.json"))
            if found:
                inv_path = found[0]
                self.work_dir = inv_path.parent
            else:
                raise FileNotFoundError(
                    f"No inventory.json found in {self.target_path}. "
                    "This parser requires archives produced by the raw-inventory collect-hwinfo.ps1."
                )

        self.inventory = json.loads(inv_path.read_text(encoding="utf-8-sig"))

    def _get_records(self, domain, name):
        """Retrieve safe records array from inventory sources."""
        src = self.inventory.get("sources", {}).get(domain, {}).get(name, {})
        if src.get("status") == "ok":
            return src.get("records", [])
        return []

    def _get_single_record(self, domain, name):
        recs = self._get_records(domain, name)
        return recs[0] if recs else {}

    def _file_path(self, rel_path):
        if not rel_path:
            return None
        rel_path = str(rel_path).replace("\\", "/")
        candidate = self.work_dir / rel_path
        if candidate.is_file():
            return candidate
        # Fallback recursive search by filename
        fn = Path(rel_path).name.lower()
        for root, _, files in os.walk(self.work_dir):
            for f in files:
                if f.lower() == fn:
                    return Path(root) / f
        return None

    def parse(self):
        self._parse_system_and_cpu()
        self._parse_display()
        self._parse_battery()
        self._compute_hwids()
        self._reconcile_and_parse_acpi()
        self._parse_pci_and_pnp()
        self._build_missing_data_checklist()
        return {"facts": self.facts, "missing": self.missing}

