def format_board_dts_template(data: dict) -> str:
    facts = data["facts"]

    mfg = facts["system"].get("manufacturer", {}).get("value", "vendor").lower().replace(" ", "-")
    model = facts["system"].get("model", {}).get("value", "board").lower().replace(" ", "-")
    soc = facts.get("soc", {})
    base_dtsi = soc.get("base_dtsi", "FIXME_BASE_SOC.dtsi")

    lines = []
    lines.append("/*")
    lines.append(" * ============================================================================")
    lines.append(" * INCOMPLETE DEVICETREE REVIEW TEMPLATE (board.dts.in)")
    lines.append(
        f" * Target: {facts['system'].get('manufacturer', {}).get('value', '')} "
        f"{facts['system'].get('model', {}).get('value', '')}"
    )
    lines.append(" *")
    lines.append(" * NOTICE: This file is intentionally incomplete and will NOT compile as-is.")
    lines.append(" * Every placeholder requires verification against Linux kernel sources,")
    lines.append(" * binding documentation, or hardware schematics.")
    lines.append(" * ============================================================================")
    lines.append(" */")
    lines.append("")
    lines.append("/dts-v1/;")
    lines.append("")
    lines.append(f"/* FIXME[KERNEL_NODE]: Verify base SoC DTSI include for {soc.get('tier', 'Unknown SoC')} */")
    lines.append(f'#include "{base_dtsi}"')
    lines.append("/* FIXME[BOARD]: Include appropriate PMIC DTSI (e.g. hamoa-pmics.dtsi) and handle overrides */")
    lines.append('#include "FIXME-pmics.dtsi"')
    lines.append("")
    lines.append("/ {")
    lines.append(
        f'\tmodel = "{facts["system"].get("manufacturer", {}).get("value", "")} '
        f'{facts["system"].get("model", {}).get("value", "")}";'
    )
    lines.append(
        "\t/* FIXME[BINDING]: Select approved compatible string from Documentation/devicetree/bindings/arm/qcom.yaml */"
    )
    lines.append(f'\tcompatible = "{mfg},{model}", "qcom,TBD";')
    lines.append('\tchassis-type = "laptop";')
    lines.append("};")
    lines.append("")

    for p in facts.get("peripherals", []):
        mmio = p.get("controller_mmio") or "UNKNOWN_MMIO"
        mmio_label = f"FIXME_I2C_{mmio.replace('0x', '').upper()}"
        ctrl_acpi = p.get("parent_acpi_controller", "UNKNOWN_CTRL")

        lines.append("/*")
        lines.append(f" * FIXME[KERNEL_NODE]: Map ACPI controller {ctrl_acpi} (MMIO {mmio}) to Linux node label.")
        lines.append(f' * Lookup: git grep -n -i "{mmio.replace("0x", "")}" arch/arm64/boot/dts/qcom/')
        lines.append(" */")
        lines.append(f"&{mmio_label} {{")

        addr = p.get("slave_address") or "0xFIXME"
        addr_clean = addr.replace("0x", "")
        role = p.get("role", "device")
        node_prefix = role if role != "unknown" else "device"
        node_name = f"{node_prefix}@{addr_clean}"
        hid = p.get("hid") or p.get("cid") or "UNKNOWN_HID"

        lines.append(f"\t{node_name} {{")
        lines.append(
            f"\t\t/* Observed ACPI device: {p['acpi_path']} (HID: {hid}, inferred role: {p.get('role', 'unknown')}) */"
        )

        if p.get("is_disabled"):
            lines.append("\t\t/* NOTE: ACPI _STA unconditionally returns Zero (disabled placeholder) */")
            lines.append('\t\tstatus = "disabled";')

        if p.get("is_hid_over_i2c"):
            lines.append('\t\tcompatible = "hid-over-i2c";')
            if p.get("hid_descr_addr"):
                lines.append(f"\t\thid-descr-addr = <{p['hid_descr_addr']}>;")
            else:
                lines.append("\t\t/* FIXME[BINDING]: HID descriptor address not found in the ACPI _DSM */")
                lines.append("\t\thid-descr-addr = <0x1>;")
        else:
            lines.append(
                "\t\t/* FIXME[BINDING]: Look up Linux compatible in "
                f"Documentation/devicetree/bindings/ for HID {hid} */"
            )
            lines.append('\t\tcompatible = "TBD";')

        lines.append(f"\t\treg = <{addr}>;")

        if p.get("interrupt_gpio"):
            ig = p["interrupt_gpio"]
            pol = ig.get("polarity", "")
            if "Edge" in pol:
                irq_type = (
                    "IRQ_TYPE_EDGE_FALLING"
                    if "Low" in pol
                    else ("IRQ_TYPE_EDGE_RISING" if "High" in pol else "IRQ_TYPE_EDGE_BOTH")
                )
            else:
                irq_type = (
                    "IRQ_TYPE_LEVEL_LOW"
                    if "Low" in pol
                    else ("IRQ_TYPE_LEVEL_HIGH" if "High" in pol else "IRQ_TYPE_EDGE_BOTH")
                )
            lines.append(
                f"\t\t/* FIXME[BOARD]: Translate raw ACPI GpioInt {ig['pin']} "
                f"({ig['direction']}, {pol}) to physical TLMM pin */"
            )
            lines.append(f"\t\tinterrupts-extended = <&FIXME_TLMM FIXME_PIN {irq_type}>;")

        if p.get("io_gpios"):
            for io in p["io_gpios"]:
                lines.append(
                    f"\t\t/* FIXME[BOARD]: Translate raw ACPI GpioIo {io['pin']} "
                    f"({io['direction']}) to reset-gpios or enable-gpios */"
                )

        lines.append("\t\t/* FIXME[BOARD]: Identify regulator supplies from board schematics */")
        lines.append("\t\tvdd-supply = <&FIXME_VDD_REGULATOR>;")
        lines.append("\t\twakeup-source;")
        lines.append("\t};")
        lines.append("};")
        lines.append("")

    gpio_devs = facts.get("gpio_devices", [])
    for g in gpio_devs:
        lines.append("/*")
        lines.append(f" * ACPI device {g['acpi_path']} (HID: {g.get('hid') or 'none'}, inferred role: {g['role']})")
        lines.append(" * FIXME[BOARD]: Translate the raw ACPI GPIO resources to physical pins:")
        for io in g["gpios"]:
            source = f", source {io['source']}" if io.get("source") else ""
            lines.append(
                f" *   {io['type']} {io['pin']} = {int(io['pin'], 16)} ({io['direction']}, "
                f"{io.get('polarity') or 'no polarity'}{source})"
            )
        lines.append(" */")
        lines.append("")

    key_devs = [g for g in gpio_devs if g["role"] in ("buttons", "lid")]
    if key_devs:
        lines.append("/ {")
        lines.append("\tgpio-keys {")
        lines.append('\t\tcompatible = "gpio-keys";')
        key_index = 0
        for g in key_devs:
            for io in g["gpios"]:
                polarity = "GPIO_ACTIVE_LOW" if "Low" in (io.get("polarity") or "") else "GPIO_ACTIVE_HIGH"
                lines.append(f"\t\tkey-{key_index} {{")
                lines.append(
                    f"\t\t\t/* FIXME[BOARD]: {g['role']} from ACPI {g['acpi_name']} {io['type']} {io['pin']}; "
                    "identify the key and the physical pin */"
                )
                lines.append(f"\t\t\tgpios = <&{gpio_label(io.get('source'))} {int(io['pin'], 16)} {polarity}>;")
                if g["role"] == "lid":
                    lines.append("\t\t\tlinux,input-type = <EV_SW>;")
                    lines.append("\t\t\tlinux,code = <SW_LID>;")
                else:
                    lines.append("\t\t\tlinux,code = <FIXME_KEY_CODE>;")
                lines.append('\t\t\tlabel = "FIXME";')
                lines.append("\t\t\twakeup-source;")
                lines.append("\t\t};")
                key_index += 1
        lines.append("\t};")
        lines.append("};")
        lines.append("")

    for g in gpio_devs:
        uart = next((s for s in g["serial"] if s["type"] == "uart"), None)
        if g["role"] != "bluetooth" or not uart:
            continue
        uart_name = uart["source"].split(".")[-1].replace("_", "")
        uart_mmio = facts.get("controllers", {}).get(uart_name, {}).get("mmio_base") or "UNKNOWN_MMIO"
        lines.append("/*")
        lines.append(f" * FIXME[KERNEL_NODE]: Map ACPI UART controller {uart['source']} (MMIO {uart_mmio}) to a label.")
        lines.append(" */")
        lines.append(f"&FIXME_UART_{uart_mmio.replace('0x', '').upper()} {{")
        lines.append("\tbluetooth {")
        lines.append("\t\t/* FIXME[BINDING]: Look up the Bluetooth chip's compatible string */")
        lines.append('\t\tcompatible = "TBD";')
        for io in g["gpios"]:
            lines.append(
                f"\t\t/* FIXME[BOARD]: raw ACPI {io['type']} {io['pin']} is probably the enable or reset line */"
            )
            lines.append(f"\t\tenable-gpios = <&{gpio_label(io.get('source'))} {int(io['pin'], 16)} GPIO_ACTIVE_HIGH>;")
        lines.append("\t};")
        lines.append("};")
        lines.append("")

    zones = facts.get("thermal_zones", [])
    if zones:
        lines.append("/ {")
        lines.append("\tthermal-zones {")
        for z in zones:
            zone = z["acpi_name"].lower()
            devices = ", ".join(z["devices"]) or "none"
            lines.append(f"\t\t{zone}-thermal {{")
            hid = z.get("hid") or "none"
            lines.append(f"\t\t\t/* ACPI ThermalZone {z['acpi_name']} (HID: {hid}, devices: {devices}) */")
            lines.append("\t\t\t/* FIXME[BOARD]: Match the sensor to a tsens channel and add cooling-maps */")
            lines.append("\t\t\tthermal-sensors = <&FIXME_TSENS FIXME_CHANNEL>;")
            if z["sampling_ms"]:
                lines.append(f"\t\t\tpolling-delay-passive = <{z['sampling_ms']}>;")
            lines.append("\t\t\ttrips {")
            for label, temperature in z["trips_mc"].items():
                lines.append(f"\t\t\t\t{zone}_{label}: {label}-trip {{")
                lines.append(f"\t\t\t\t\ttemperature = <{temperature}>;")
                lines.append("\t\t\t\t\thysteresis = <0>;")
                lines.append(f'\t\t\t\t\ttype = "{label}";')
                lines.append("\t\t\t\t};")
            lines.append("\t\t\t};")
            lines.append("\t\t};")
        lines.append("\t};")
        lines.append("};")
        lines.append("")

    usb_ports = facts.get("usb_ports", [])
    if usb_ports:
        lines.append("/*")
        lines.append(" * ACPI USB ports (_UPC and _PLD).")
        lines.append(" * FIXME[BOARD]: Use them to describe the USB controllers, connectors and internal devices.")
        for port in usb_ports:
            loc = port.get("location")
            if loc:
                visible = "user visible" if loc["user_visible"] else "not user visible"
                where = f"{loc['panel']} {loc['vertical']}/{loc['horizontal']}, {loc['shape']}, {visible}"
            else:
                where = "no location"
            kind = "internal" if port["internal"] else "external"
            address = f"{port['acpi_path']} (port {port['port_address']})"
            lines.append(f" *   {address}: {port['connector']}, {kind}, {where}")
        lines.append(" */")
        lines.append("")

    wifi = facts.get("wifi")
    if wifi:
        vid = wifi.get("vendor_id", "17cb")
        did = wifi.get("device_id", "FIXME")
        port = wifi.get("dt_pcie_port") or "&FIXME_PCIE_PORT"
        lines.append("/*")
        lines.append(f" * Observed PCI ID: VEN_{vid.upper()}&DEV_{did.upper()}")
        lines.append(
            f" * Resolved name: {wifi.get('caption', 'Wi-Fi')} ({wifi.get('caption_source', 'unknown source')})"
        )
        if wifi.get("location_paths"):
            lines.append(f" * Location: {wifi['location_paths']}")
        lines.append(f" * Root port: {port}")
        lines.append(f' * Lookup: git grep -n "{vid},{did}" arch/arm64/boot/dts/qcom/')
        lines.append(" */")
        lines.append(f"{port} {{")
        lines.append("\twifi@0 {")
        lines.append(f'\t\tcompatible = "pci{vid},{did}";')
        lines.append("\t\treg = <0x10000 0x0 0x0 0x0 0x0>;")
        lines.append("\t\t/* FIXME[BOARD]: Wi-Fi PMU regulator supplies (vddaon-supply, etc.) */")
        lines.append("\t};")
        lines.append("};")
        lines.append("")

    eth = facts.get("ethernet")
    if eth:
        vid = eth.get("vendor_id", "10ec")
        did = eth.get("device_id", "8168")
        port = eth.get("dt_pcie_port") or "&FIXME_PCIE_ETHERNET"
        lines.append("/*")
        lines.append(f" * Observed Ethernet PCI ID: {vid}:{did} on {port}")
        lines.append(f" * Resolved name: {eth.get('caption', 'NIC')} ({eth.get('caption_source', 'unknown source')})")
        lines.append(" */")
        lines.append(f"{port} {{")
        lines.append('\tstatus = "okay";')
        lines.append("};")
        lines.append("")

    disp = facts.get("display", {})
    timing = disp.get("timing")
    lines.append("/*")
    lines.append(f" * Observed display panel EDID: {disp.get('panel_edid_id', 'Unknown')}")
    if timing:
        dimensions = ""
        if timing.get("width_mm") is not None and timing.get("height_mm") is not None:
            dimensions = f", {timing['width_mm']}mm x {timing['height_mm']}mm"
        lines.append(
            f" * Preferred timing: {timing['width_pixels']}x{timing['height_pixels']} "
            f"@ {timing['refresh_rate_hz']} Hz (pixel clock: {timing['pixel_clock_mhz']} MHz{dimensions})"
        )
    else:
        edid_issue = next(
            (
                m
                for m in data["missing"]
                if m.get("category") in ("TOOL_MISSING", "EDID_DECODE_ERROR") and "EDID" in m.get("item", "").upper()
            ),
            None,
        )
        if edid_issue:
            lines.append(f" * FIXME[TOOL]: {edid_issue['instruction']}")
    if disp.get("is_oled"):
        lines.append(" * NOTE: Panel is OLED. Do NOT define a pwm-backlight node (uses DPCD AUX backlight).")
        lines.append(" */")
    else:
        lines.append(" * FIXME[BINDING]: Look up panel compatible in Documentation/devicetree/bindings/display/panel/")
        lines.append(" * FIXME[BOARD]: Backlight PWM frequency and enable GPIO are board-specific.")
        lines.append(" */")
        lines.append("/ {")
        lines.append("\tbacklight: backlight {")
        lines.append('\t\tcompatible = "pwm-backlight";')
        lines.append("\t\tpwms = <&FIXME_PWM_CONTROLLER FIXME_CHANNEL FIXME_PERIOD_NS>;")
        lines.append("\t\tenable-gpios = <&FIXME_GPIO_CONTROLLER FIXME_PIN GPIO_ACTIVE_HIGH>;")
        lines.append("\t};")
        lines.append("};")

    return "\n".join(lines)


def format_hwids_txt(data: dict) -> str:
    hwids = data["facts"].get("hwids", {})
    computer_info = hwids.get("computer_info", {})

    lines = ["Computer Information", "--------------------"]
    for name in (
        "BiosVendor",
        "BiosVersion",
        "BiosMajorRelease",
        "BiosMinorRelease",
        "FirmwareMajorRelease",
        "FirmwareMinorRelease",
        "Manufacturer",
        "Family",
        "ProductName",
        "ProductSku",
        "EnclosureKind",
        "BaseboardManufacturer",
        "BaseboardProduct",
    ):
        val = computer_info.get(name, {}).get("value")
        lines.append(f"{name}: {val if val is not None else ''}")

    lines.extend(("Hardware IDs", "------------"))
    for entry in hwids.get("hardware_ids", []):
        lines.append(f"{{{entry['guid']}}}   <- {entry['description']}")

    return "\n".join(lines)


def format_markdown_report(data: dict) -> str:
    facts = data["facts"]
    missing = data["missing"]

    lines = []
    lines.append(
        f"# Hardware Specification Report: {facts['system'].get('manufacturer', {}).get('value', '')} "
        f"{facts['system'].get('model', {}).get('value', '')}\n"
    )

    lines.append("## 1. Verified Hardware Observations (Facts)")
    lines.append("| Category | Property | Observed Value | Source Provenance | Status |")
    lines.append("|---|---|---|---|---|")

    sys_info = facts["system"]
    lines.append(
        f"| Platform | Manufacturer | `{sys_info.get('manufacturer', {}).get('value', '')}` | "
        f"{sys_info.get('manufacturer', {}).get('source', '')} | "
        f"{sys_info.get('manufacturer', {}).get('status', '')} |"
    )
    lines.append(
        f"| Platform | Model | `{sys_info.get('model', {}).get('value', '')}` | "
        f"{sys_info.get('model', {}).get('source', '')} | {sys_info.get('model', {}).get('status', '')} |"
    )
    if sys_info.get("sku", {}).get("value"):
        lines.append(
            f"| Platform | System SKU | `{sys_info['sku']['value']}` | "
            f"{sys_info['sku']['source']} | {sys_info['sku']['status']} |"
        )
    if sys_info.get("baseboard_product", {}).get("value"):
        lines.append(
            f"| Platform | BaseBoard Product | `{sys_info['baseboard_product']['value']}` | "
            f"{sys_info['baseboard_product']['source']} | {sys_info['baseboard_product']['status']} |"
        )
    lines.append(
        f"| Platform | BIOS Version | `{sys_info.get('bios_version', {}).get('value', '')}` | "
        f"{sys_info.get('bios_version', {}).get('source', '')} | "
        f"{sys_info.get('bios_version', {}).get('status', '')} |"
    )

    cpu = facts.get("processor", {})
    if cpu:
        lines.append(f"| CPU | Processor | `{cpu.get('name', '')}` | {cpu.get('source', '')} | verified |")

    soc = facts.get("soc", {})
    if soc:
        lines.append(
            f"| SoC | Tier / SKU | `{soc.get('tier', '')}` | {soc.get('status', '')} | {soc.get('status', '')} |"
        )

    disp = facts.get("display", {})
    lines.append(
        f"| Display | Panel EDID ID | `{disp.get('panel_edid_id', '')}` | "
        f"{disp.get('source', '')} | {disp.get('status', '')} |"
    )
    lines.append(
        f"| Display | Panel Technology | `{'OLED' if disp.get('is_oled') else 'IPS / LCD'}` | "
        f"{disp.get('source', '')} | inferred |"
    )
    timing = disp.get("timing")
    if timing:
        timing_source = timing.get("source", disp.get("source", ""))
        lines.append(
            f"| Display | Native Mode | `{timing['width_pixels']}x{timing['height_pixels']} "
            f"@ {timing['refresh_rate_hz']} Hz` | {timing_source} | {timing.get('status', 'observed')} |"
        )
        if timing.get("width_mm") is not None and timing.get("height_mm") is not None:
            lines.append(
                f"| Display | Physical Dimensions | `{timing['width_mm']} mm x {timing['height_mm']} mm` | "
                f"{timing_source} | {timing.get('status', 'observed')} |"
            )

    bat = facts.get("battery", {})
    if bat.get("model_name") and bat.get("model_name") != "Unknown":
        lines.append(f"| Battery | Model Name | `{bat.get('model_name')}` | {bat.get('source')} | observed |")
        lines.append(
            f"| Battery | Design Capacity | `{bat.get('design_capacity_mwh')} mWh` | {bat.get('source')} | observed |"
        )

    periphs = facts.get("peripherals", [])
    pci_devs = facts.get("pci_devices", [])
    lines.append("\n## 2. Hardware Topology Tree (Synthesized)")
    lines.append("```text")
    lines.append("Platform Hardware Root")

    controllers_seen = {}
    for p in periphs:
        c = p.get("parent_acpi_controller") or "Unknown_Controller"
        if c not in controllers_seen:
            controllers_seen[c] = []
        controllers_seen[c].append(p)

    c_keys = list(controllers_seen.keys())
    if c_keys:
        lines.append("├── ACPI Serial Controllers:")
        for c_idx, c_name in enumerate(c_keys):
            is_last_c = c_idx == len(c_keys) - 1
            c_branch = "└── " if is_last_c else "├── "
            c_indent = "    " if is_last_c else "│   "
            mmio = controllers_seen[c_name][0].get("controller_mmio") or "Unknown MMIO"
            lines.append(f"│   {c_branch}{c_name} (MMIO {mmio})")

            child_list = controllers_seen[c_name]
            for ch_idx, ch in enumerate(child_list):
                is_last_ch = ch_idx == len(child_list) - 1
                ch_branch = "└── " if is_last_ch else "├── "
                hid_desc = ch.get("hid") or ch.get("cid") or "Unknown"
                ig = ch.get("interrupt_gpio")
                gpio_desc = f", GpioInt: Pin {ig['pin']}" if ig else ""
                status_desc = " [disabled]" if ch.get("is_disabled") else f" [{ch['role_status']}]"
                lines.append(
                    f"│   {c_indent}{ch_branch}{ch['role']:<15} "
                    f"@{ch.get('slave_address', 'Unknown'):<6} ({hid_desc}{gpio_desc}){status_desc}"
                )

    if pci_devs:
        lines.append("└── PCIe Root Ports & Endpoints:")
        for p_idx, pdev in enumerate(pci_devs):
            is_last_p = p_idx == len(pci_devs) - 1
            p_branch = "└── " if is_last_p else "├── "
            port_label = pdev.get("dt_pcie_port") or pdev.get("acpi_root_port") or "PCIe Slot"
            lines.append(f"    {p_branch}{port_label:<16} [{pdev['vendor_id']}:{pdev['device_id']}] {pdev['caption']}")

    lines.append("```")

    if periphs:
        lines.append("\n## 3. Discovered Peripheral Nodes (from ACPICA Hardware Map)")
        lines.append(
            "| Role | ACPI Path | Parent Controller (MMIO) | Slave Address | Speed | HID / CID | Interrupt | Status |"
        )
        lines.append("|---|---|---|---|---|---|---|---|")
        for p in periphs:
            hid = p.get("hid") or ("Dynamic (-Method-)" if p.get("dynamic_hid") else (p.get("cid") or "N/A"))
            ig = p.get("interrupt_gpio")
            gpio_str = f"Pin {ig['pin']} ({ig['polarity']})" if ig else "None"
            mmio = p.get("controller_mmio") or "Unknown MMIO"
            speed = f"{p.get('speed_hz')} Hz" if p.get("speed_hz") else "N/A"
            status = "disabled" if p.get("is_disabled") else "active"
            lines.append(
                f"| {p['role']} | `{p['acpi_path']}` | `{p.get('parent_acpi_controller', '')}` (`{mmio}`) | "
                f"`{p.get('slave_address', '')}` | {speed} | `{hid}` | {gpio_str} | {status} |"
            )

    gpio_devs = facts.get("gpio_devices", [])
    if gpio_devs:
        lines.append("\n### Other ACPI GPIO Consumers")
        lines.append("| Role | ACPI Path | HID | GPIO Resources (raw pin) | Serial Bus | Source |")
        lines.append("|---|---|---|---|---|---|")
        for g in gpio_devs:
            pins = ", ".join(f"{io['type']} {io['pin']}" for io in g["gpios"])
            serial = ", ".join(f"{s['type']} `{s['source']}`" for s in g["serial"]) or "None"
            lines.append(
                f"| {g['role']} | `{g['acpi_path']}` | `{g.get('hid') or 'N/A'}` | {pins} | {serial} | {g['source']} |"
            )

    zones = facts.get("thermal_zones", [])
    if zones:
        lines.append("\n### ACPI Thermal Zones")
        lines.append("| Zone | HID | Passive | Hot | Critical | Sampling | Devices |")
        lines.append("|---|---|---|---|---|---|---|")
        for z in zones:
            trips = {k: f"{v / 1000:.2f} C" for k, v in z["trips_mc"].items()}
            sampling = f"{z['sampling_ms']} ms" if z["sampling_ms"] else "N/A"
            lines.append(
                f"| {z['acpi_name']} | `{z.get('hid') or 'N/A'}` | {trips.get('passive', '-')} | "
                f"{trips.get('hot', '-')} | {trips.get('critical', '-')} | {sampling} | "
                f"{', '.join(z['devices']) or 'none'} |"
            )

    usb_ports = facts.get("usb_ports", [])
    if usb_ports:
        lines.append("\n### ACPI USB Ports")
        lines.append("| ACPI Path | Port | Connector | Placement | Location |")
        lines.append("|---|---|---|---|---|")
        for port in usb_ports:
            loc = port.get("location")
            where = f"{loc['panel']} {loc['vertical']}/{loc['horizontal']}, {loc['shape']}" if loc else "N/A"
            lines.append(
                f"| `{port['acpi_path']}` | {port['port_address']} | {port['connector'] or 'N/A'} | "
                f"{'internal' if port['internal'] else 'external'} | {where} |"
            )

    acpi_props = facts.get("acpi_properties", [])
    if acpi_props:
        lines.append("\n### ACPI Device Properties (_DSD)")
        lines.append("| ACPI Path | Property | Value | UUID |")
        lines.append("|---|---|---|---|")
        for dev in acpi_props:
            for prop in dev["properties"]:
                lines.append(f"| `{dev['acpi_path']}` | `{prop['name']}` | `{prop['value']}` | `{prop['uuid']}` |")

    usb_devs = facts.get("usb_devices", [])
    if pci_devs or usb_devs:
        lines.append("\n## 4. PCI & USB Endpoint Inventory")
        if pci_devs:
            lines.append("### PCIe Endpoints")
            lines.append(
                "| Endpoint Name | Vendor:Device | Subsystem | Class | Root Port / Location | Name Source | Status |"
            )
            lines.append("|---|---|---|---|---|---|---|")
            for p in pci_devs:
                port = p.get("dt_pcie_port") or p.get("acpi_root_port") or "Unknown"
                sub = p.get("subsystem_id") or "N/A"
                lines.append(
                    f"| {p['caption']} | `{p['vendor_id']}:{p['device_id']}` | `{sub}` | {p['class']} | "
                    f"`{port}` | {p.get('caption_source', p.get('source', ''))} | {p['status']} |"
                )

        if usb_devs:
            lines.append("\n### USB Endpoints")
            lines.append("| Endpoint Name | VID:PID | Class | Name Source | Status |")
            lines.append("|---|---|---|---|---|")
            for u in usb_devs:
                lines.append(
                    f"| {u['caption']} | `{u['vendor_id']}:{u['product_id']}` | {u['class']} | "
                    f"{u.get('caption_source', u.get('source', ''))} | {u['status']} |"
                )

    lines.append("\n## 5. Checklist of Required Lookups (Missing Data)")
    lines.append("| Lookup Category | Item Required | Instructions / Lookup Command |")
    lines.append("|---|---|---|")
    for m in missing:
        cat = m.get("lookup_type", m.get("category", "TBD"))
        item = m.get("item", m.get("subsystem", "Unknown"))
        instr = m.get("instruction", m.get("message", ""))
        lines.append(f"| **{cat}** | {item} | {instr} |")

    return "\n".join(lines)


