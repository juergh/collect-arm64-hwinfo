    @classmethod
    def _decode_pld(cls, data):
        if len(data) < 10:
            return None
        return {
            "user_visible": bool(data[8] & 0x01),
            "dock": bool(data[8] & 0x02),
            "lid": bool(data[8] & 0x04),
            "panel": cls.PLD_PANELS[(data[8] >> 3) & 0x07],
            "vertical": ("upper", "center", "lower", "unknown")[(data[8] >> 6) & 0x03],
            "horizontal": ("left", "center", "right", "unknown")[data[9] & 0x03],
            "shape": cls.PLD_SHAPES[min((data[9] >> 2) & 0x0F, len(cls.PLD_SHAPES) - 1)],
        }

    @staticmethod
    def _returned_payload(dsl, method_body, inline_pattern, named_pattern):
        if method_body is None:
            return None
        m = re.search(inline_pattern, method_body)
        if m:
            return m.group(1)
        ref = re.search(r"Return\s*\(\s*\\?_SB\.(?:\w+\.)*(\w+)\s*\)", method_body)
        if ref:
            m = re.search(named_pattern.replace("NAME", re.escape(ref.group(1))), dsl.text)
            if m:
                return m.group(1)
        return None

    def _decode_usb_ports(self, dsl):
        ports = []
        for _, dev_open in dsl.devices():
            upc_method = dsl.own_method(dev_open, "_UPC")
            if upc_method is None:
                continue
            head = re.split(r"\bDevice\s*\(", dsl.body(dev_open), maxsplit=1)[0]
            adr = re.search(r"Name\s*\(\s*_ADR\s*,\s*(0x[0-9A-Fa-f]+|One|Zero)\s*\)", head)
            port = {
                "acpi_path": dsl.path(dev_open),
                "port_address": self._acpi_int(adr.group(1)) if adr else None,
                "connectable": None,
                "connector": None,
                "location": None,
                "source": "DSDT.dsl",
                "status": "observed",
            }

            upc = self._returned_payload(
                dsl,
                upc_method,
                r"Package\s*\(\s*0x0?4\s*\)\s*\{([^{}]*)\}",
                r"Name\s*\(\s*NAME\s*,\s*Package\s*\(\s*0x0?4\s*\)\s*\{([^{}]*)\}",
            )
            if upc:
                values = [self._acpi_int(t) for t in re.findall(r"0x[0-9A-Fa-f]+|One|Zero|\d+", upc)]
                if len(values) >= 2:
                    port["connectable"] = bool(values[0])
                    port["connector"] = self.USB_CONNECTORS.get(values[1], f"type 0x{values[1]:x}")

            pld = self._returned_payload(
                dsl,
                dsl.own_method(dev_open, "_PLD"),
                r"Buffer\s*\([^)]*\)\s*\{([^{}]*)\}",
                r"Name\s*\(\s*NAME\s*,\s*Package\s*\([^)]*\)\s*\{\s*Buffer\s*\([^)]*\)\s*\{([^{}]*)\}",
            )
            if pld:
                port["location"] = self._decode_pld(bytes(int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]{2})", pld)))

            visible = port["location"]["user_visible"] if port["location"] else None
            port["internal"] = port["connectable"] is False or visible is False
            ports.append(port)
        return ports

    @staticmethod
    def _decode_device_properties(dsl):
        devices = []
        for _, dev_open in dsl.devices():
            dsd = dsl.own_block(dev_open, r"Name\s*\(\s*_DSD\s*,\s*Package[^{]*\{")
            if dsd is None:
                continue
            uuids = [(m.start(), m.group(1).lower()) for m in re.finditer(r'ToUUID\s*\(\s*"([0-9A-Fa-f-]+)"\s*\)', dsd)]
            properties = []
            for m in re.finditer(r'Package\s*\(\s*0x0?2\s*\)\s*\{\s*"([^"]+)"\s*,\s*([^{}]*?)\s*\}', dsd):
                uuid = next((u for pos, u in reversed(uuids) if pos < m.start()), None)
                value = re.sub(r"/\*.*?\*/", "", m.group(2)).strip().rstrip(",").strip()
                properties.append({"uuid": uuid, "name": m.group(1), "value": value})
            if properties:
                devices.append(
                    {
                        "acpi_path": dsl.path(dev_open),
                        "properties": properties,
                        "source": "DSDT.dsl",
                        "status": "observed",
                    }
                )
        return devices

