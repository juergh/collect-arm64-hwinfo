    def _parse_display(self):
        monitors = self._get_records("root/wmi", "WmiMonitorID")
        edid_arts = self.inventory.get("artifacts", {}).get("edid", [])

        # Parse primary monitor (index 0)
        edid_entry = edid_arts[0] if edid_arts else {}
        edid_path = self._file_path(edid_entry.get("path"))

        mfg_str = ""
        prod_str = ""
        friendly_str = ""

        if monitors:
            m0 = monitors[0]
            mfg_bytes = [b for b in (m0.get("ManufacturerName") or []) if b != 0]
            prod_bytes = [b for b in (m0.get("ProductCodeID") or []) if b != 0]
            ufn_bytes = [b for b in (m0.get("UserFriendlyName") or []) if b != 0]
            if mfg_bytes:
                mfg_str = bytes(mfg_bytes).decode("ascii", "replace").strip()
            if prod_bytes:
                prod_str = bytes(prod_bytes).decode("ascii", "replace").strip()
            if ufn_bytes:
                friendly_str = bytes(ufn_bytes).decode("ascii", "replace").strip()

        edid_chid, edid_chid_source = self._get_single_edid_id()

        is_oled = True if (mfg_str in ["SDC", "SEC"]) else False
        timing_info = self._decode_edid(edid_path)

        panel_id = f"{mfg_str}{prod_str}" if mfg_str and prod_str else "Unknown"
        self.facts["display"] = {
            "manufacturer_code": mfg_str or "Unknown",
            "product_code": prod_str or "Unknown",
            "panel_edid_id": panel_id,
            "chid_panel_id": edid_chid,
            "chid_panel_id_source": edid_chid_source,
            "friendly_name": friendly_str or None,
            "raw_edid_path": str(edid_path.relative_to(self.work_dir)) if edid_path else None,
            "timing": timing_info,
            "is_oled": is_oled,
            "source": "inventory.json:WmiMonitorID + edid/",
            "status": "observed" if mfg_str else "unknown",
        }

    def _parse_battery(self):
        b_cim = self._get_single_record("root/cimv2", "Win32_Battery")
        b_port = self._get_single_record("root/cimv2", "Win32_PortableBattery")
        b_static = self._get_single_record("root/wmi", "BatteryStaticData")
        b_full = self._get_single_record("root/wmi", "BatteryFullChargedCapacity")

        # Clean model name
        raw_name = b_static.get("DeviceName") or b_cim.get("Name") or ""
        clean_model = re.sub(r"[^\x20-\x7E]", "", raw_name).strip() or "Unknown"

        # Manufacturer
        mfg = b_port.get("Manufacturer")
        clean_mfg = re.sub(r"[^\x20-\x7E]", "", mfg).strip() if mfg else None

        # Chemistry
        chem_label = "Unknown"
        raw_chem = b_static.get("Chemistry")
        if raw_chem:
            try:
                chem_str = int(raw_chem).to_bytes(4, "little").decode("ascii", "replace").strip()
                if re.match(r"^[A-Za-z0-9 ]{2,4}$", chem_str):
                    chem_label = chem_str
            except Exception:
                pass

        if chem_label == "Unknown" and b_cim.get("Chemistry"):
            chem_label = BATTERY_CHEMISTRY_NAMES.get(b_cim["Chemistry"], str(b_cim["Chemistry"]))

        design_cap = b_static.get("DesignedCapacity") or b_cim.get("DesignCapacity")
        full_cap = b_full.get("FullChargedCapacity") or b_cim.get("FullChargeCapacity")

        self.facts["battery"] = {
            "model_name": clean_model,
            "manufacturer": clean_mfg,
            "chemistry": chem_label,
            "design_capacity_mwh": int(design_cap) if design_cap else None,
            "full_charge_capacity_mwh": int(full_cap) if full_cap else None,
            "source": "inventory.json:Battery*",
            "status": "observed" if clean_model != "Unknown" else "unknown",
        }

    def _get_single_edid_id(self):
        """Return stubble's EDID CHID component when exactly one valid panel is captured."""
        edid_arts = self.inventory.get("artifacts", {}).get("edid", [])
        panels = []
        for art in edid_arts:
            p = self._file_path(art.get("path"))
            if not p or not p.is_file():
                continue
            try:
                blob = p.read_bytes()
            except OSError:
                continue
            if len(blob) < 128 or blob[:8] != b"\x00\xff\xff\xff\xff\xff\xff\x00":
                continue

            manufacturer_id = int.from_bytes(blob[8:10], byteorder="big")
            manufacturer = []
            for index in range(3):
                letter = (manufacturer_id >> (5 * index)) & 0x1F
                if letter > 26:
                    break
                manufacturer.insert(0, chr(letter + ord("A") - 1))
            else:
                product_code = int.from_bytes(blob[10:12], byteorder="little")
                try:
                    source = str(p.relative_to(self.work_dir))
                except ValueError:
                    source = p.name
                panels.append((f"{''.join(manufacturer)}{product_code:04x}", source))

        return panels[0] if len(panels) == 1 else (None, None)

    @staticmethod
    def _generate_chid(values):
        if not all(values):
            return None

        encoded = "&".join(values).encode("utf-16-le")
        raw = bytearray(hashlib.sha1(CHID_NAMESPACE.bytes + encoded).digest()[:16])
        raw[6] = (raw[6] & 0x0F) | 0x50
        raw[8] = (raw[8] & 0x3F) | 0x80
        return str(uuid.UUID(bytes=bytes(raw)))

    def _compute_hwids(self):
        system = self.facts["system"]
        display = self.facts["display"]
        system_keys = {
            "BiosVendor": "bios_manufacturer",
            "BiosVersion": "bios_version",
            "BiosMajorRelease": "bios_major_release",
            "BiosMinorRelease": "bios_minor_release",
            "FirmwareMajorRelease": "firmware_major_release",
            "FirmwareMinorRelease": "firmware_minor_release",
            "Manufacturer": "manufacturer",
            "Family": "family",
            "ProductName": "product_name",
            "ProductSku": "sku",
            "EnclosureKind": "chassis_type",
            "BaseboardManufacturer": "baseboard_manufacturer",
            "BaseboardProduct": "baseboard_product",
        }

        computer_info = {}
        for name, key in system_keys.items():
            fact = dict(system.get(key, {}))
            if fact.get("status") == "unknown":
                fact["value"] = None
            computer_info[name] = fact
        computer_info["EDID"] = {
            "value": display.get("chid_panel_id"),
            "source": display.get("chid_panel_id_source"),
            "status": "observed" if display.get("chid_panel_id") else "unknown",
        }

        hardware_ids = []
        for level, fields, description in CHID_DEFINITIONS:
            values = []
            for field in fields:
                val = computer_info.get(field, {}).get("value")
                if val is None:
                    values = None
                    break
                if field in ("BiosMajorRelease", "BiosMinorRelease"):
                    try:
                        val = f"{int(val):02x}"
                    except (ValueError, TypeError):
                        values = None
                        break
                values.append(str(val))
            chid = self._generate_chid(values) if values else None
            if not chid:
                continue
            sources = sorted(
                {computer_info[field].get("source") for field in fields if computer_info.get(field, {}).get("source")}
            )
            hardware_ids.append(
                {
                    "level": level,
                    "guid": chid,
                    "fields": list(fields),
                    "description": description,
                    "source": sources,
                    "status": "inferred",
                }
            )

        self.facts["hwids"] = {
            "namespace": str(CHID_NAMESPACE),
            "computer_info": computer_info,
            "hardware_ids": hardware_ids,
        }

    def _decode_edid(self, edid_path):
        """Decode the captured EDID binary with edid-decode (trimming registry padding first)."""
        if not edid_path or not edid_path.is_file():
            return None

        try:
            raw_bytes = edid_path.read_bytes()
        except OSError as e:
            self.missing.append(
                {
                    "category": "EDID_DECODE_ERROR",
                    "item": "Display EDID read",
                    "lookup_type": "TOOL",
                    "instruction": str(e),
                }
            )
            return None

        if len(raw_bytes) < 128 or raw_bytes[:8] != b"\x00\xff\xff\xff\xff\xff\xff\x00":
            return None

        # Trim registry padding to declared blocks (base block + extension count at byte 126)
        declared_blocks = min(1 + raw_bytes[126], len(raw_bytes) // 128)
        input_data = raw_bytes[: declared_blocks * 128]
        source = str(edid_path.relative_to(self.work_dir))

        decoder = shutil.which("edid-decode")
        if not decoder:
            self.missing.append(
                {
                    "category": "TOOL_MISSING",
                    "item": "edid-decode",
                    "lookup_type": "TOOL",
                    "instruction": "Install 'edid-decode' to extract display timings from the captured EDID.",
                }
            )
            return None

        # On Windows, passing binary via stdin ('-') can fail due to text-mode translation;
        # write the trimmed blocks to a temporary file instead.
        timing = None
        with tempfile.NamedTemporaryFile(delete=False, suffix=".bin") as tf:
            tf.write(input_data)
            temp_bin_path = tf.name

        try:
            command = [decoder, "--skip-hex-dump", "--preferred-timings", temp_bin_path]
            result = subprocess.run(command, capture_output=True, check=False)
        except OSError as e:
            self.missing.append(
                {
                    "category": "EDID_DECODE_ERROR",
                    "item": "Display EDID timing",
                    "lookup_type": "TOOL",
                    "instruction": f"edid-decode could not process {source}: {e}",
                }
            )
            return None
        finally:
            try:
                os.unlink(temp_bin_path)
            except OSError:
                pass

        output = result.stdout.decode("utf-8", errors="replace")
        if result.returncode != 0:
            error = result.stderr.decode("utf-8", errors="replace").strip()
            self.missing.append(
                {
                    "category": "EDID_DECODE_ERROR",
                    "item": "Display EDID timing",
                    "lookup_type": "TOOL",
                    "instruction": f"edid-decode could not process {source}: {error or 'unknown error'}",
                }
            )
            return None

        preferred = output.split("Preferred Video Timing", 1)[-1]
        timing = re.search(
            r"(?:DTD|VIC)\s+\d+:\s+(\d+)x(\d+)(?:i)?\s+([0-9.]+)\s+Hz"
            r".*?([0-9.]+)\s+MHz(?:\s+\((\d+)\s+mm\s+x\s+(\d+)\s+mm\))?",
            preferred,
        )
        if not timing:
            self.missing.append(
                {
                    "category": "EDID_DECODE_ERROR",
                    "item": "Display preferred timing",
                    "lookup_type": "TOOL",
                    "instruction": f"edid-decode found no preferred timing in {source}.",
                }
            )
            return None

        width_mm = int(timing.group(5)) if timing.group(5) else None
        height_mm = int(timing.group(6)) if timing.group(6) else None
        if width_mm is None or height_mm is None:
            image_size = re.search(r"Maximum image size:\s+(\d+)\s+cm\s+x\s+(\d+)\s+cm", output)
            if image_size:
                width_mm = int(image_size.group(1)) * 10
                height_mm = int(image_size.group(2)) * 10

        return {
            "width_pixels": int(timing.group(1)),
            "height_pixels": int(timing.group(2)),
            "refresh_rate_hz": round(float(timing.group(3)), 3),
            "width_mm": width_mm,
            "height_mm": height_mm,
            "pixel_clock_mhz": round(float(timing.group(4)), 3),
            "source": f"{source} via edid-decode",
            "status": "observed",
        }

    # -------------------------------------------------------------------------
    # 3. ACPI Reconciliation, Decompilation & Topology Extraction
    # -------------------------------------------------------------------------
    def _reconcile_and_parse_acpi(self):
        acpi_arts = self.inventory.get("artifacts", {}).get("acpi", [])
        if not acpi_arts:
            return

        # Create temporary staging directory for reconciled tables and iasl outputs
        if not self.acpi_staging_dir:
            self.acpi_staging_dir = tempfile.mkdtemp(prefix="iasl_staging_")

        staging = Path(self.acpi_staging_dir)

        # De-duplicate tables by SHA-256. Prefer registry tables for DSDT.
        # Order: registry first so DSDT/SSDTs are prioritized, then firmware-api.
        sorted_arts = sorted(acpi_arts, key=lambda a: 0 if a.get("source") == "registry" else 1)

        seen_hashes = set()
        sig_counts = {}
        dsdt_dat = None

        for art in sorted_arts:
            p = self._file_path(art.get("path"))
            if not p or not p.is_file():
                continue
            data = p.read_bytes()
            if len(data) < 36:
                continue

            h = hashlib.sha256(data).hexdigest()
            if h in seen_hashes:
                continue
            seen_hashes.add(h)

            sig = art.get("signature") or data[:4].decode("ascii", "replace")
            idx = sig_counts.get(sig, 0)
            sig_counts[sig] = idx + 1
            out_name = f"{sig}.dat" if idx == 0 else f"{sig}{idx}.dat"
            dest = staging / out_name
            dest.write_bytes(data)

            if sig == "DSDT" and dsdt_dat is None:
                dsdt_dat = dest

        if not dsdt_dat:
            return

        # Run iasl -d -lm on DSDT
        iasl_bin = shutil.which("iasl")
        if not iasl_bin:
            self.missing.append(
                {
                    "category": "TOOL_MISSING",
                    "item": "iasl (acpica-tools)",
                    "lookup_type": "TOOL",
                    "instruction": "Install 'acpica-tools' or 'acpica' to generate ACPICA hardware map and ASL.",
                }
            )
            return

        prefix = str(staging / "dsdt")
        try:
            subprocess.run(
                [iasl_bin, "-d", "-lm", "-p", prefix, str(dsdt_dat)],
                cwd=self.acpi_staging_dir,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )
        except Exception as e:
            self.missing.append(
                {"category": "DECOMPILE_ERROR", "file": dsdt_dat.name, "error": str(e), "lookup_type": "TOOL"}
            )
            return

        map_path = Path(f"{prefix}.map")
        dsl_path = Path(f"{prefix}.dsl")

        if not dsl_path.is_file():
            return

        map_text = map_path.read_text(encoding="utf-8", errors="replace") if map_path.is_file() else ""
        dsl_text = dsl_path.read_text(encoding="utf-8", errors="replace")

        dsl_index = DslIndex(dsl_text)

        # 3a. Extract MMIO base addresses for controllers from DSDT.dsl (Memory32Fixed)
        for m in re.finditer(
            r"Device\s*\(\s*([A-Za-z0-9_]+)\s*\)\s*\{([\s\S]*?Method\s*\(\s*_CRS[\s\S]*?Return\s*\(\s*\w+\s*\)[\s\S]*?\})",
            dsl_text,
        ):
            cname = m.group(1)
            body = m.group(2)
            mem_m = re.search(r"Memory32Fixed\s*\(\s*\w+\s*,[\s\S]*?(0x[0-9A-Fa-f]+)[\s\S]*?(0x[0-9A-Fa-f]+)", body)
            irq_m = re.search(r"Interrupt\s*\([^\{]+\{\s*(0x[0-9A-Fa-f]+|\d+)\s*\}", body)
            if mem_m:
                self.facts["controllers"][cname] = {
                    "acpi_path": f"\\_SB.{cname}",
                    "mmio_base": hex(int(mem_m.group(1), 0)).lower(),
                    "mmio_length": hex(int(mem_m.group(2), 0)),
                    "interrupt": hex(int(irq_m.group(1), 0)) if irq_m else None,
                    "source": "DSDT.dsl",
                    "status": "observed",
                }

        # Decode raw _CRS buffers, thermal zones, USB ports, _DSD
        raw_devices = self._decode_raw_crs_devices(dsl_index)
        dsl_devices = {}
        for dev_name, dev_open in dsl_index.devices():
            dsl_devices.setdefault(dev_name, dev_open)

        self.facts["thermal_zones"] = self._decode_thermal_zones(dsl_index)
        self.facts["usb_ports"] = self._decode_usb_ports(dsl_index)
        self.facts["acpi_properties"] = self._decode_device_properties(dsl_index)

        for dev in raw_devices:
            if dev["memory"] and dev["name"] not in self.facts["controllers"]:
                mem = dev["memory"][0]
                self.facts["controllers"][dev["name"]] = {
                    "acpi_path": f"\\_SB.{dev['name']}",
                    "mmio_base": hex(mem["base"]),
                    "mmio_length": hex(mem["length"]),
                    "interrupt": hex(dev["interrupts"][0]) if dev["interrupts"] else None,
                    "source": "DSDT.dsl (raw _CRS buffer)",
                    "status": "observed",
                }

        # 3b. Parse GPIO Table from .map
        gpio_by_dest = {}
        in_gpio = False
        for line in map_text.splitlines():
            if line.startswith("Pin   Type     Direction"):
                in_gpio = True
                continue
            if in_gpio:
                if not line.strip() or "Controller:" in line or "Resource Descriptor" in line:
                    if "Controller:" not in line:
                        in_gpio = False
                    continue
                if len(line) >= 55 and line[0:4].strip().isalnum():
                    pin = line[0:4].strip()
                    gtype = line[6:13].strip()
                    direction = line[15:26].strip()
                    polarity = line[28:38].strip()
                    dest_hid = line[40:50].strip()
                    raw_dest = line[51:].split()[0].strip()
                    dest_path = raw_dest.replace("_SB_.", "\\_SB.").replace("_SB_\\", "\\_SB.")
                    dest_path = re.sub(r"\b([A-Za-z0-9]+)_\b", r"\1", dest_path)

                    if dest_path not in gpio_by_dest:
                        gpio_by_dest[dest_path] = []
                    gpio_by_dest[dest_path].append(
                        {
                            "pin": f"0x{int(pin, 16):x}",
                            "type": gtype,
                            "direction": direction,
                            "polarity": polarity,
                            "dest_hid": dest_hid,
                        }
                    )

        # 3c. Parse Serial Controllers & Peripherals from .map
        current_ctrl = None
        for line in map_text.splitlines():
            if "Controller:" in line and len(line) >= 28 and line[0:4].strip() in ("I2C", "SPI", "UART"):
                btype = line[0:4].strip().lower()
                chid = line[18:27].strip()
                cpath = line[28:].strip().split()[0]
                cname = cpath.split(".")[-1].replace("_", "")
                ctrl_info = self.facts["controllers"].get(cname, {})
                current_ctrl = {
                    "type": btype,
                    "hid": chid,
                    "path": cpath,
                    "name": cname,
                    "mmio": ctrl_info.get("mmio_base"),
                }
                continue

            if line.startswith("Type  Address   Speed"):
                continue

            if current_ctrl and len(line) >= 38 and line[0:4].strip().lower() == current_ctrl["type"]:
                btype = line[0:4].strip().lower()
                addr = line[6:11].strip()
                speed = line[14:23].strip()
                dest_hid = line[26:36].strip()
                raw_dest = line[37:].split()[0].strip()
                dest_path = raw_dest.replace("_SB_.", "\\_SB.").replace("_SB_\\", "\\_SB.")
                dest_path = re.sub(r"\b([A-Za-z0-9]+)_\b", r"\1", dest_path)
                dname = dest_path.split(".")[-1]

                if dest_hid == "-Field-":
                    continue

                slave_addr = f"0x{int(addr, 16):x}" if addr.isalnum() else addr
                speed_hz = int(speed, 16) if speed.isalnum() else 0

                cid = None
                is_disabled = False
                cid_m = re.search(
                    rf"Device\s*\(\s*{dname}\s*\)[\s\S]*?Name\s*\(\s*_CID\s*,\s*\"([A-Za-z0-9]+)\"", dsl_text
                )
                if cid_m:
                    cid = cid_m.group(1)

                sta_m = re.search(
                    rf"Device\s*\(\s*{dname}\s*\)[\s\S]*?Method\s*\(\s*_STA[^{{]*\{{([\s\S]*?)\}}", dsl_text
                )
                if sta_m:
                    sta_body = sta_m.group(1)
                    if "0x0F" in sta_body or "0x0B" in sta_body or "0xF" in sta_body:
                        is_disabled = False
                    elif re.search(r"Return\s*\(\s*(?:Zero|0x00?)\s*\)", sta_body) and "If" not in sta_body:
                        is_disabled = True

                is_hid_over_i2c = bool(cid == "PNP0C50")
                hid_descr_addr = None
                if is_hid_over_i2c and dname in dsl_devices:
                    hid_descr_addr = self._hid_descriptor_address(dsl_index.own_method(dsl_devices[dname], "_DSM"))

                inferred_role = self._infer_role(dname, slave_addr, is_hid_over_i2c)

                gpios = gpio_by_dest.get(dest_path, [])
                int_gpios = [g for g in gpios if g["type"] == "GpioInt"]
                io_gpios = [g for g in gpios if g["type"] == "GpioIo"]

                self.facts["peripherals"].append(
                    {
                        "acpi_name": dname,
                        "acpi_path": dest_path,
                        "bus_type": btype,
                        "role": inferred_role,
                        "role_status": "inferred" if inferred_role != "unknown" else "unknown",
                        "hid": dest_hid if dest_hid not in ("-No HID-", "-Method-") else None,
                        "dynamic_hid": bool(dest_hid == "-Method-"),
                        "cid": cid,
                        "is_hid_over_i2c": is_hid_over_i2c,
                        "hid_descr_addr": f"0x{hid_descr_addr:x}" if hid_descr_addr is not None else None,
                        "is_disabled": is_disabled,
                        "parent_acpi_controller": current_ctrl["path"],
                        "controller_mmio": current_ctrl["mmio"],
                        "slave_address": slave_addr,
                        "speed_hz": speed_hz,
                        "interrupt_gpio": int_gpios[0] if int_gpios else None,
                        "all_interrupt_gpios": int_gpios,
                        "io_gpios": io_gpios,
                        "source": "DSDT.map",
                        "status": "observed",
                    }
                )

        # 3d. Add raw _CRS decoded I2C peripherals
        known_peripherals = {(p["acpi_path"], p["slave_address"]) for p in self.facts["peripherals"]}
        for dev in raw_devices:
            for i2c in dev["i2c"]:
                dpath = f"\\_SB.{dev['name']}"
                slave_addr = f"0x{i2c['address']:x}"
                if (dpath, slave_addr) in known_peripherals:
                    continue

                cname = i2c["source"].split(".")[-1].replace("_", "")
                is_hid_over_i2c = dev["cid"] == "PNP0C50"
                gpios = [self._raw_gpio_entry(g) for g in dev["gpios"]]
                int_gpios = [g for g in gpios if g["type"] == "GpioInt"]
                io_gpios = [g for g in gpios if g["type"] == "GpioIo"]

                self.facts["peripherals"].append(
                    {
                        "acpi_name": dev["name"],
                        "acpi_path": dpath,
                        "bus_type": "i2c",
                        "role": self._infer_role(dev["name"], slave_addr, is_hid_over_i2c),
                        "role_status": "inferred",
                        "hid": dev["hid"],
                        "hid_candidates": dev["hid_candidates"],
                        "dynamic_hid": dev["hid"] is None and bool(dev["hid_candidates"]),
                        "cid": dev["cid"],
                        "is_hid_over_i2c": is_hid_over_i2c,
                        "hid_descr_addr": (
                            f"0x{dev['hid_descr_addr']:x}" if dev["hid_descr_addr"] is not None else None
                        ),
                        "is_disabled": dev["disabled"],
                        "parent_acpi_controller": i2c["source"],
                        "controller_mmio": self.facts["controllers"].get(cname, {}).get("mmio_base"),
                        "slave_address": slave_addr,
                        "speed_hz": i2c["speed"],
                        "interrupt_gpio": int_gpios[0] if int_gpios else None,
                        "all_interrupt_gpios": int_gpios,
                        "io_gpios": io_gpios,
                        "source": "DSDT.dsl (raw _CRS buffer)",
                        "status": "observed",
                    }
                )
                known_peripherals.add((dpath, slave_addr))

        # 3e. GPIO consumers that are not I2C peripherals
        for dev in raw_devices:
            if not dev["gpios"] or dev["i2c"]:
                continue
            self.facts["gpio_devices"].append(
                {
                    "acpi_name": dev["name"],
                    "acpi_path": f"\\_SB.{dev['name']}",
                    "hid": dev["hid"],
                    "role": self._infer_gpio_role(dev["name"], dev["hid"]),
                    "gpios": [self._raw_gpio_entry(g) for g in dev["gpios"]],
                    "serial": dev["serial"],
                    "controller_mmio": self.facts["controllers"].get(dev["name"], {}).get("mmio_base"),
                    "source": "DSDT.dsl (raw _CRS buffer)",
                    "status": "observed",
                }
            )

        claimed = {p["acpi_path"].replace("\\\\", "\\") for p in self.facts["peripherals"]}
        claimed |= {g["acpi_path"] for g in self.facts["gpio_devices"]}
        for dest_path, gpios in gpio_by_dest.items():
            path = dest_path.replace("\\\\", "\\")
            if path in claimed:
                continue
            name = path.split(".")[-1]
            self.facts["gpio_devices"].append(
                {
                    "acpi_name": name,
                    "acpi_path": path,
                    "hid": None,
                    "role": self._infer_gpio_role(name, None),
                    "gpios": [{**g, "source": None} for g in gpios],
                    "serial": [],
                    "controller_mmio": None,
                    "source": "DSDT.map",
                    "status": "observed",
                }
            )

    @staticmethod
    def _infer_gpio_role(name, hid):
        upper = name.upper()
        if hid == "ACPI0011" or upper.startswith("BTN"):
            return "buttons"
        if hid == "PNP0C0D" or "LID" in upper:
            return "lid"
        for prefix, role in (
            ("BTH", "bluetooth"),
            ("SDC", "sd-card"),
            ("CAM", "camera"),
            ("AUC", "audio"),
            ("AUD", "audio"),
            ("RP", "pcie-port"),
            ("PCI", "pcie-port"),
            ("UAR", "uart"),
            ("UR", "uart"),
        ):
            if upper.startswith(prefix):
                return role
        return "unknown"

    @staticmethod
    def _infer_role(dname, slave_addr, is_hid_over_i2c):
        if is_hid_over_i2c:
            if dname in ("TCPD", "TPD0", "TPL0") or slave_addr in ("0x15", "0x2c"):
                return "touchpad"
            if dname in ("TSC1", "TPL1") or slave_addr in ("0x10", "0x5d"):
                return "touchscreen"
            if dname in ("ECKB", "KBD0"):
                return "keyboard"
            return "hid-device"
        if dname.startswith("SAR"):
            return "sar-sensor"
        if dname in ("PML0", "PS8830"):
            return "typec-retimer"
        return "unknown"

    @staticmethod
    def _raw_gpio_entry(gpio):
        flags = gpio["flags"]
        if gpio["type"] == "GpioInt":
            edge = "Edge" if flags & 0x1 else "Level"
            polarity = {0: "Active High", 1: "Active Low", 2: "Active Both"}.get((flags >> 1) & 0x3, "")
            return {
                "pin": f"0x{gpio['pin']:x}",
                "type": "GpioInt",
                "direction": "Input",
                "polarity": f"{edge} {polarity}".strip(),
                "dest_hid": "",
                "source": gpio.get("source"),
            }
        return {
            "pin": f"0x{gpio['pin']:x}",
            "type": "GpioIo",
            "direction": {1: "Input", 2: "Output"}.get(flags & 0x3, "Both I/O"),
            "polarity": "",
            "dest_hid": "",
            "source": gpio.get("source"),
        }

    @staticmethod
    def _decode_resource_buffer(data):
        res = {"memory": [], "interrupts": [], "i2c": [], "serial": [], "gpios": []}
        i = 0
        while i < len(data):
            tag = data[i]
            if not tag & 0x80:
                if (tag >> 3) == 0x0F:
                    break
                i += 1 + (tag & 0x07)
                continue
            if i + 3 > len(data):
                break
            length = data[i + 1] | (data[i + 2] << 8)
            desc = data[i : i + 3 + length]
            i += 3 + length
            kind = tag & 0x7F

            if kind == 0x06 and len(desc) >= 12:
                res["memory"].append(
                    {"base": int.from_bytes(desc[4:8], "little"), "length": int.from_bytes(desc[8:12], "little")}
                )
            elif kind == 0x09 and len(desc) >= 9:
                res["interrupts"].append(int.from_bytes(desc[5:9], "little"))
            elif kind == 0x0E and len(desc) >= 18 and desc[5] == 1:
                source_offset = 12 + (desc[10] | (desc[11] << 8))
                res["i2c"].append(
                    {
                        "speed": int.from_bytes(desc[12:16], "little"),
                        "address": int.from_bytes(desc[16:18], "little"),
                        "source": desc[source_offset:].split(b"\0")[0].decode("ascii", "replace"),
                    }
                )
            elif kind == 0x0E and len(desc) >= 18 and desc[5] in (2, 3):
                source_offset = 12 + (desc[10] | (desc[11] << 8))
                res["serial"].append(
                    {
                        "type": "spi" if desc[5] == 2 else "uart",
                        "speed": int.from_bytes(desc[12:16], "little"),
                        "source": desc[source_offset:].split(b"\0")[0].decode("ascii", "replace"),
                    }
                )
            elif kind == 0x0C and len(desc) >= 23:
                pin_offset = int.from_bytes(desc[14:16], "little")
                name_offset = int.from_bytes(desc[17:19], "little")
                for offset in range(pin_offset, name_offset, 2):
                    res["gpios"].append(
                        {
                            "type": "GpioInt" if desc[4] == 0 else "GpioIo",
                            "flags": int.from_bytes(desc[7:9], "little"),
                            "pin": int.from_bytes(desc[offset : offset + 2], "little"),
                            "source": desc[name_offset:].split(b"\0")[0].decode("ascii", "replace"),
                        }
                    )
        return res

    @staticmethod
    def _hid_descriptor_address(dsm):
        if not dsm:
            return None
        uuid = re.search(r'ToUUID\s*\(\s*"3cdff6f7-4267-4555-ad05-b30a3d8938de"\s*\)', dsm)
        if not uuid:
            return None
        m = re.search(
            r"\(\(\s*(?:Arg2|_T_\d+)\s*==\s*(?:One|0x0?1)\s*\)\)\s*\{"
            r"[^{}]*?Return\s*\(\s*(0x[0-9A-Fa-f]+|Zero|One|\d+)\s*\)",
            dsm[uuid.end() :],
        )
        if not m:
            return None
        return HwInfoParser._acpi_int(m.group(1))

    def _decode_raw_crs_devices(self, dsl):
        devices = []
        for name, dev_open in dsl.devices():
            crs = dsl.own_method(dev_open, "_CRS")
            if crs is None:
                continue
            buf = re.search(r"Name\s*\(\s*(\w+)\s*,\s*Buffer\s*\([^)]*\)\s*\{([^{}]*)\}", crs)
            if not buf or not re.search(rf"Return\s*\(\s*{buf.group(1)}\s*\)", crs):
                continue
            data = bytes(int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]{2})", buf.group(2)))
            res = self._decode_resource_buffer(data)
            if not (res["memory"] or res["i2c"] or res["serial"] or res["gpios"]):
                continue

            head = re.split(r"\bDevice\s*\(", dsl.body(dev_open), maxsplit=1)[0]
            cid = re.search(r'Name\s*\(\s*_CID\s*,\s*"([A-Za-z0-9]+)"', head)
            hid = re.search(r'Name\s*\(\s*_HID\s*,\s*"([A-Za-z0-9]+)"', head)
            hid_method = dsl.own_method(dev_open, "_HID")
            sta = dsl.own_method(dev_open, "_STA")
            disabled = bool(
                sta
                and not re.search(r"0x0?[Ff]\b|0x0[Bb]\b", sta)
                and re.search(r"Return\s*\(\s*(?:Zero|0x00?)\s*\)", sta)
                and "If" not in sta
            )
            devices.append(
                {
                    "name": name,
                    "cid": cid.group(1) if cid else None,
                    "hid": hid.group(1) if hid else None,
                    "hid_candidates": re.findall(r'Return\s*\(\s*"([A-Za-z0-9]+)"', hid_method) if hid_method else [],
                    "hid_descr_addr": self._hid_descriptor_address(dsl.own_method(dev_open, "_DSM")),
                    "disabled": disabled,
                    **res,
                }
            )
        return devices

    @staticmethod
    def _acpi_int(token):
        return {"Zero": 0, "One": 1}[token] if token in ("Zero", "One") else int(token, 0)

    @staticmethod
    def _decode_thermal_zones(dsl):
        zones = []
        for name, zone_open in dsl.objects("ThermalZone"):
            body = dsl.body(zone_open)

            def named_int(var):
                m = re.search(rf"Name\s*\(\s*{var}\s*,\s*(0x[0-9A-Fa-f]+|One|Zero)\s*\)", body)
                return HwInfoParser._acpi_int(m.group(1)) if m else 0

            trips = {}
            for label, var in (("passive", "TPSV"), ("hot", "THOT"), ("critical", "TCRT")):
                val = named_int(var)
                if val:
                    temperature = val * 100 - 273150
                    if temperature <= 200000:
                        trips[label] = temperature
            if not trips:
                continue

            hid = re.search(r'Name\s*\(\s*_HID\s*,\s*"([^"]+)"', body)
            tzd = re.search(r"Name\s*\(\s*_TZD\s*,\s*Package[^{]*\{([^{}]*)\}", body)
            zones.append(
                {
                    "acpi_name": name,
                    "hid": hid.group(1) if hid else None,
                    "trips_mc": trips,
                    "sampling_ms": named_int("TTSP") * 100,
                    "devices": list(dict.fromkeys(re.findall(r"\\_SB\.(\w+)", tzd.group(1)))) if tzd else [],
                    "source": "DSDT.dsl",
                    "status": "observed",
                }
            )
        return zones

